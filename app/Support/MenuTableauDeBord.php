    /**
     * Toutes les routes de menu, à plat.
     *
     * @return array<int, string>
     */
    public static function routes(): array
    {
        return collect(self::sections())
            ->flatMap(fn (array $section) => collect($section[1])->pluck(0))
            ->values()
            ->all();
    }

    /**
     * Libellé d'un menu, ou sa route si elle n'est plus au menu.
     */
    public static function libelle(string $route): string
    {
        foreach (self::sections() as [$titre, $liens]) {
            foreach ($liens as $lien) {
                if ($lien[0] === $route) {
                    return $lien[1];
                }
            }
        }

        return $route;
    }

    /**
     * L'accueil, toujours accessible.
     *
     * Un employé sans aucun droit doit tout de même pouvoir se connecter et
     * atterrir quelque part, faute de quoi il tourne en boucle sur un refus.
     */
    public const TOUJOURS_OUVERT = ['admin.index'];

    /**
     * Menus visibles par cet utilisateur.
     *
     * Un administrateur voit tout : lui retirer des menus reviendrait à créer un
     * tableau de bord que personne ne peut administrer entièrement.
     *
     * @return array<int, array{0: string, 1: array<int, array{0: string, 1: string, 2: string}>}>
     */
    public static function pourUtilisateur(?\App\Models\User $utilisateur): array
    {
        if (! $utilisateur || $utilisateur->role === 'admin') {
            return self::sections();
        }

        $accordes = self::droitsDe($utilisateur);

        return collect(self::sections())
            ->map(fn (array $section) => [
                $section[0],
                collect($section[1])
                    ->filter(fn (array $lien) => in_array($lien[0], $accordes, true))
                    ->values()
                    ->all(),
            ])
            // Une section vidée de tous ses liens ne doit pas laisser un titre
            // orphelin dans la barre.
            ->filter(fn (array $section) => count($section[1]) > 0)
            ->values()
            ->all();
    }

    /**
     * Routes autorisées pour cet utilisateur, l'accueil compris.
     *
     * @return array<int, string>
     */
    public static function droitsDe(\App\Models\User $utilisateur): array
    {
        if ($utilisateur->role === 'admin') {
            return self::routes();
        }

        return \App\Models\MenuPermission::where('user_id', $utilisateur->id)
            ->pluck('menu')
            ->merge(self::TOUJOURS_OUVERT)
            ->unique()
            ->values()
            ->all();
    }

    /**
     * Cet utilisateur peut-il ouvrir cette route ?
     */
    public static function autorise(?\App\Models\User $utilisateur, ?string $route): bool
    {
        if (! $utilisateur) {
            return false;
        }

        if ($utilisateur->role === 'admin') {
            return true;
        }

        /*
         | Une route hors menu reste ouverte.
         |
         | Le tableau de bord compte des pages qui ne figurent pas dans la barre
         | — actions POST, flux de rafraîchissement, sous-pages. Les refuser
         | faute de droit explicite casserait des écrans auxquels l'employé a
         | pourtant accès.
         */
        if ($route === null || ! in_array($route, self::routes(), true)) {
            return true;
        }

        return in_array($route, self::droitsDe($utilisateur), true);
    }
